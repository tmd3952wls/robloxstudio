def _rig(s):
    groups, torso, *piv = s.split("|")
    out = {"g": {i + 1: g for i, g in enumerate(groups.split(","))}, "T": int(torso)}
    for key, p in zip(("LA", "RA", "LL", "RL", "HD"), piv):
        idx, xyz = p.split(":")
        out[key] = (int(idx), tuple(float(v) for v in xyz.split(",")))
    return out


